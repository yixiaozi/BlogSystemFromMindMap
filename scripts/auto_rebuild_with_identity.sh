#!/bin/bash
# Improved auto rebuild blog on mindmap commit with Hermes Agent identity

set -e

cd /data/mindmaps || exit 1

# Add all changes
if ! git add -A; then
  echo "Failed to add changes"
  exit 1
fi

# Pull remote latest with rebase
if ! git pull --rebase origin master; then
  echo "Pull failed, stashing changes..."
  git stash
  git pull --rebase origin master
  git stash pop
fi

# Check if there are changes to commit
if git diff-index --quiet HEAD --; then
  echo "No changes to commit"
else
  msg="Auto rebuild blog on mindmap commit by Hermes Agent. Changed files:\n"
  msg+=$(git diff --name-only HEAD)
  git config user.name "Hermes Agent"
  git config user.email "hermes@agent.local"
  git commit -m "$msg"
  git push origin master
fi

# Regenerate blog website
cd /root/BlogSystemFromMindMap || exit 1

# Replace with actual build commands
mkdir -p ./public
 echo "Built at $(date)" > ./public/build.log

# Add, commit and push blog changes
if ! git add ./public/build.log; then
  echo "Failed to add blog build files"
  exit 1
fi

if git diff-index --quiet HEAD --; then
  echo "No blog changes to commit"
else
  git commit -m "Auto rebuild blog on mindmap update by Hermes Agent"
  git push origin master
fi

exit 0






































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































